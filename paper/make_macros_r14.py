"""v14 macros (structural screen struct_r1, cooling handover ramp HA, confirmed vs v13) -> paper/results_macros_r14.tex.

    python paper/make_macros_r14.py
Sources: experiments/results/struct_r1/{screen_*.json, decision_HA_v13fresh.json, frost_hs18_HA.json}.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
S = ROOT / "experiments" / "results" / "struct_r1"
d = json.loads((S / "decision_HA_v13fresh.json").read_text(encoding="utf-8"))
fr = json.loads((S / "frost_hs18_HA.json").read_text(encoding="utf-8"))
screens = sorted(S.glob("screen_*.json"))


def spct(x, nd=2):
    return ("$-$" if x < 0 else "$+$") + f"{abs(100 * x):.{nd}f}\\%"


def apct(x, nd=2):
    return f"{abs(100 * x):.{nd}f}\\%"


assert d["complete"] and d["mixture_ci"][1] < 0 and d["pub30"] <= 0, "HA confirmation must have passed"
reg = d["hh_regret_per_step"]
M = {
    "RFtNScreen": len(screens),
    "RFtMix": spct(d["mixture"]), "RFtMixAbs": apct(d["mixture"]),
    "RFtMixLo": spct(d["mixture_ci"][0]), "RFtMixHi": spct(d["mixture_ci"][1]),
    "RFtMixLoAbs": apct(d["mixture_ci"][0]), "RFtMixHiAbs": apct(d["mixture_ci"][1]),
    "RFtHCThree": spct(d["hc3"]), "RFtHH": spct(d["hh"]), "RFtPub": spct(d["pub30"]), "RFtPubAbs": apct(d["pub30"]),
    "RFtHHWins": f"{d['hh_wins']}/{d['n']['r10hh']}", "RFtHCThreeWins": f"{d['hc3_wins']}/{d['n']['r10hc']}",
    "RFtPubWins": f"{d['pub30_wins']}/{d['n']['pub30']}",
    "RFtHHRegretCut": f"{abs(100 * (1 - reg['HA'] / reg['v13'])):.0f}\\%",
}
ha, v13 = fr["HA_hs18"], fr["v13ref_hs18"]
M["RFtColdest"] = f"{ha['coldest_c']:.1f}"
M["RFtColdestVThirteen"] = f"{v13['coldest_c']:.1f}"
M["RFtBelowFive"] = f"{100 * ha['below5_share']:.2f}\\%"
M["RFtBelowFiveVThirteen"] = f"{100 * v13['below5_share']:.2f}\\%"
kag = json.loads((ROOT / "experiments" / "results" / "kaggle_feedback.json").read_text(encoding="utf-8"))
M["RFtKagVFourteen"] = f"{kag['scores_by_policy']['v14_HA']:.5f}"
lines = ["% generated by paper/make_macros_r14.py; do not edit"]
lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in M.items()]
(ROOT / "paper" / "results_macros_r14.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(M), "macros;", sorted(fr)[:8])
